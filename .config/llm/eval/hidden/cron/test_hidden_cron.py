@pytest.mark.parametrize("expr,after,expected", CASES)
def test_hidden(expr, after, expected):
    assert next_run(expr, datetime.fromisoformat(after)) == datetime.fromisoformat(expected)


@pytest.mark.parametrize("expr", ["* * 0 * *", "* * 32 * *", "* * * 13 *", "* * * * 8", "1,,2 * * * *",
                                  "*/-1 * * * *", "a * * * *", "* * * * * *", "", "1-2-3 * * * *"])
def test_hidden_invalid(expr):
    with pytest.raises(ValueError):
        next_run(expr, datetime(2026, 1, 1))


def test_seconds_zeroed_and_strictly_after():
    assert next_run("* * * * *", datetime(2026, 3, 1, 10, 0, 0)) == datetime(2026, 3, 1, 10, 1)
    assert next_run("* * * * *", datetime(2026, 3, 1, 10, 0, 59, 999)) == datetime(2026, 3, 1, 10, 1)


def test_dom_dow_or():
    # Friday the 13th style: 13th OR Friday
    assert next_run("0 0 13 * 5", datetime(2026, 11, 1)) == datetime(2026, 11, 6)
